// ============================================
// Expr.h
// ============================================
// Этот файл содержит все классы для построения дерева выражений:
//   - Number      (число)
//   - Variable    (переменная)
//   - BiOperation (бинарная операция: +, -, *, /)
//   - Assign      (присваивание: a = 5)
//
// А также фабричные функции для удобного создания объектов:
//   - num()    - создаёт число
//   - var()    - создаёт переменную
//   - binOp()  - создаёт бинарную операцию
//   - assign() - создаёт присваивание
// ============================================

#pragma once  // Защита от двойного включения файла

#include "Visitor.h"  // Подключаем базовый класс Visitor (нужен для метода accept)
#include <string>     // Для работы с именами переменных (std::string)
#include <map>        // Для хранения переменных (в CalcVisitor)
#include <stdexcept>  // Для исключений (деление на ноль, неинициализированная переменная)
#include <iostream>   // Для вывода (в PrintVisitor)


// ============================================
// БАЗОВЫЙ КЛАСС Expr
// ============================================
// Абстрактный класс, от которого наследуются все выражения.
// Содержит чисто виртуальный метод accept(), который принимает визитора.
// 
// Зачем нужен Expr? Чтобы мы могли хранить разные типы выражений
// (числа, переменные, операции) в одном указателе Expr*.
// ============================================

class Expr {
public:
    virtual ~Expr() = default;  // Виртуальный деструктор (нужен для правильного удаления)

    // Метод accept — "дверь" для визитора.
    // Каждый наследник переопределяет этот метод и вызывает
    // соответствующий метод у визитора (visitNumber, visitVariable и т.д.)
    virtual int accept(Visitor* v) = 0;  // = 0 означает "чисто виртуальный" (абстрактный)
};


// ============================================
// КЛАСС Number (Число)
// ============================================
// Представляет число. Это лист дерева (у него нет детей).
// Пример: 5, 42, 100
// ============================================

class Number : public Expr {
    int val;  // Значение числа (например, 5)

public:
    // Конструктор: запоминаем значение
    Number(int _val) : val(_val) {}

    // Геттер: возвращает значение числа
    int getVal() const { return val; }

    // Принимаем визитора.
    // Говорим: "Эй, визитор, вызови у себя метод visitNumber и передай меня"
    virtual int accept(Visitor* v) override {
        return v->visitNumber(this);
    }
};


// ============================================
// КЛАСС Variable (Переменная)
// ============================================
// Представляет переменную. Тоже лист дерева.
// Пример: a, b, x, y
// Значение переменной хранится не здесь, а в таблице переменных (в CalcVisitor).
// ============================================

class Variable : public Expr {
    std::string name;  // Имя переменной (например, "a")

public:
    // Конструктор: запоминаем имя
    Variable(const std::string& _name) : name(_name) {}

    // Геттер: возвращает имя переменной
    std::string getName() const { return name; }

    // Принимаем визитора
    virtual int accept(Visitor* v) override {
        return v->visitVariable(this);
    }
};


// ============================================
// КЛАСС BiOperation (Бинарная операция)
// ============================================
// Представляет бинарную операцию (операцию с двумя операндами).
// Это узел дерева, у которого есть два ребёнка: левый и правый.
// Пример: a + b, x - 5, (a + b) * c
//
// Дерево для выражения (10 + 20) + 30 выглядит так:
//         '+'
//        /   \
//      '+'    30
//     /   \
//   10    20
// ============================================

class BiOperation : public Expr {
    char op;      // Оператор: '+', '-', '*', '/'
    Expr* l;      // Левый операнд (тоже выражение)
    Expr* r;      // Правый операнд (тоже выражение)

public:
    // Конструктор: запоминаем оператор и оба операнда
    BiOperation(char _op, Expr* _l, Expr* _r) : op(_op), l(_l), r(_r) {}

    // Принимаем визитора
    virtual int accept(Visitor* v) override {
        return v->visitBiOperation(this);
    }

    // Геттеры для доступа к операндам и оператору
    Expr* left() const { return l; }
    Expr* right() const { return r; }
    char getOp() const { return op; }
};


// ============================================
// КЛАСС Assign (Присваивание)
// ============================================
// Представляет операцию присваивания значения переменной.
// Имеет левую часть (имя переменной) и правую (выражение).
// Пример: a = 5, b = a + 4
//
// При вычислении: сначала вычисляется правая часть,
// потом результат сохраняется в таблице переменных.
// ============================================

class Assign : public Expr {
    std::string varName;  // Имя переменной (например, "a")
    Expr* value;          // Выражение, значение которого присваивается (например, num(5))

public:
    // Конструктор: запоминаем имя переменной и выражение-значение
    Assign(const std::string& name, Expr* val) : varName(name), value(val) {}

    // Геттеры
    std::string getVarName() const { return varName; }
    Expr* getValue() const { return value; }

    // Принимаем визитора
    virtual int accept(Visitor* v) override {
        return v->visitAssign(this);
    }
};


// ============================================
// ФАБРИЧНЫЕ ФУНКЦИИ
// ============================================
// Это просто удобные обёртки для создания объектов.
// Вместо new Number(5) пишем num(5) — короче и понятнее.
// static означает, что функция будет существовать отдельно в каждом .cpp файле,
// что позволяет избежать ошибок линковки при подключении этого .h в несколько мест.
// ============================================

// Создаёт число
static Expr* num(int val) {
    return new Number(val);
}

// Создаёт переменную
static Expr* var(const std::string& name) {
    return new Variable(name);
}

// Создаёт бинарную операцию (левый операнд, оператор, правый операнд)
static Expr* binOp(char op, Expr* left, Expr* right) {
    return new BiOperation(op, left, right);
}

// Создаёт присваивание
static Expr* assign(const std::string& name, Expr* val) {
    return new Assign(name, val);
}